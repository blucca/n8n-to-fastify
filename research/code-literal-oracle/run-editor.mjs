import { readFile, writeFile, mkdir, mkdtemp } from 'node:fs/promises';
import { resolve, join, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const [binaryArg, fileArg, outArg, checkSourceArg] = process.argv.slice(2);
assert(binaryArg && fileArg && outArg && checkSourceArg);
const binary = resolve(binaryArg), file = resolve(fileArg), out = resolve(outArg);
const { runtimeEnv, command } = await import(pathToFileURL(resolve(checkSourceArg)));
const { executionFrom } = await import(pathToFileURL(join(dirname(resolve(checkSourceArg)), 'report.mjs')));
const workflow = JSON.parse(await readFile(file, 'utf8'));
await mkdir(out, { recursive: true });
const home = await mkdtemp(join(out, 'home-')); await mkdir(join(home, 'tmp'));
const env = { ...runtimeEnv(home), NODE_OPTIONS: '--max-old-space-size=512' };
const imported = await command(binary, ['import:workflow', `--input=${file}`], env, 60000);
await writeFile(join(out, 'import.json'), JSON.stringify(imported, null, 2));
assert.equal(imported.exitCode, 0, imported.stdout + imported.stderr);
const executed = await command(binary, ['execute', `--id=${workflow.id}`, '--rawOutput'], env, 60000);
await writeFile(join(out, 'execute.json'), JSON.stringify(executed, null, 2));
const execution = executionFrom(executed.stdout + '\n' + executed.stderr);
await writeFile(join(out, 'execution.json'), JSON.stringify(execution, null, 2));
assert.equal(executed.exitCode, 0, executed.stdout + executed.stderr);
assert(execution && !execution.data.resultData.error, 'editor workflow failed');
const runs = execution.data.resultData.runData;
const rows = name => (runs[name]?.[0]?.data?.main?.[0] ?? []).map(x => x.json);
const final = rows('Check expected output');
assert.deepEqual(rows('Next'), [{ text: 'line one\nline two', next: true }]);
assert.deepEqual(final, [{ status: 'passed', checks: [{ node: 'Next', output: 0, count: 1, passed: true }] }]);
const result = { passed: true, nodes: workflow.nodes.length, runOrder: Object.keys(runs), next: rows('Next'), final };
await writeFile(join(out, 'result.json'), JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify(result));
